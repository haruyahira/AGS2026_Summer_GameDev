#pragma once

#include <string>
#include <vector>

//--------------------------------------------------
// ランキング記録
//--------------------------------------------------
struct RankingRecord
{
    //---------------------------------
    // プレイヤー名
    //---------------------------------
    std::string name;

    //---------------------------------
    // 獲得金額
    //---------------------------------
    int money;
};

//--------------------------------------------------
// ランキング管理クラス
//--------------------------------------------------
class RankingManager
{
public:
    //---------------------------------
    // 最大ランキング件数
    //---------------------------------
    static constexpr int MAX_RANKING_COUNT = 10;

    //---------------------------------
    // 名前の最大バイト数
    //---------------------------------
    static constexpr int MAX_NAME_BYTE_LENGTH = 64;

public:
    //---------------------------------
    // インスタンス取得
    //---------------------------------
    static RankingManager& GetInstance(void);

    //---------------------------------
    // 初期化
    //---------------------------------
    void Init(void);

    //---------------------------------
    // 読み込み
    //---------------------------------
    void Load(void);

    //---------------------------------
    // 再読み込み
    //---------------------------------
    void Reload(void);

    //---------------------------------
    // 保存
    //---------------------------------
    void Save(void) const;

    //---------------------------------
    // 全記録削除
    //---------------------------------
    void Clear(void);

    //---------------------------------
    // 名前と金額を登録する
    //
    // 戻り値:
    // 1～10 : ランクイン
    // -1    : ランキング外
    //---------------------------------
    int RegisterRecord(
        const std::string& name,
        int money
    );

    //---------------------------------
    // 指定順位の記録を取得
    //---------------------------------
    const RankingRecord* GetRecord(
        int rank
    ) const;

    //---------------------------------
    // 指定順位の名前を取得
    //---------------------------------
    std::string GetName(
        int rank
    ) const;

    //---------------------------------
    // 指定順位の金額を取得
    //---------------------------------
    int GetMoney(
        int rank
    ) const;

    //---------------------------------
    // 全ランキング取得
    //---------------------------------
    const std::vector<RankingRecord>&
        GetRanking(void) const;

    //---------------------------------
    // 件数取得
    //---------------------------------
    int GetRankingCount(void) const;

private:
    //---------------------------------
    // コンストラクタ
    //---------------------------------
    RankingManager(void);

    //---------------------------------
    // デストラクタ
    //---------------------------------
    ~RankingManager(void) = default;

    //---------------------------------
    // コピー禁止
    //---------------------------------
    RankingManager(
        const RankingManager&
    ) = delete;

    //---------------------------------
    // コピー代入禁止
    //---------------------------------
    RankingManager& operator=(
        const RankingManager&
        ) = delete;

private:
    //---------------------------------
    // 保存先フォルダー
    //---------------------------------
    static constexpr const char* SAVE_DIRECTORY =
        "Data/Save";

    //---------------------------------
    // 保存先ファイル
    //---------------------------------
    static constexpr const char* SAVE_FILE_PATH =
        "Data/Save/Ranking.dat";

    //---------------------------------
    // セーブデータ識別子
    //---------------------------------
    static constexpr unsigned int FILE_MAGIC =
        0x52414E4B;

    //---------------------------------
    // セーブデータ形式のバージョン
    //---------------------------------
    static constexpr unsigned int FILE_VERSION =
        2;

private:
    //---------------------------------
    // ランキング記録
    //---------------------------------
    std::vector<RankingRecord> ranking_;

    //---------------------------------
    // 読み込み済みか
    //---------------------------------
    bool isLoaded_;
};